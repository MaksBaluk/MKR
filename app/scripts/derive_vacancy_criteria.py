"""Write fixtures/vacancy_criteria.json: D_vga (`criterion_ids`) per requirement alternative of fixtures/vacancies.json.

vacancies.json stays byte-identical (the original 90 are hash-guarded); the mapping lives beside it, keyed by the
alternative id the seed assigns (`<group id>-a<n>`). Deterministic and idempotent.
Run from app/: uv run python scripts/derive_vacancy_criteria.py"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from backend.domain.vacancy_criteria import CRITERIA_SOURCE, derive_required_criteria  # noqa: E402

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures"


def main() -> int:
    rubrics = {r["action_id"]: [c["criterion_id"] for c in r["criteria"]]
               for r in json.loads((FIXTURES / "rubrics.json").read_text(encoding="utf-8"))["rubrics"]}
    vacancies = json.loads((FIXTURES / "vacancies.json").read_text(encoding="utf-8"))
    real = FIXTURES / "vacancies_real.json"
    if real.exists():  # imported postings: same rule, the criteria are still rule-derived, not employer data
        vacancies += json.loads(real.read_text(encoding="utf-8"))
    requirements = {}
    for v in vacancies:
        for g in v["groups"]:
            for index, a in enumerate(g["alternatives"]):
                requirements[f"{g['id']}-a{index + 1}"] = derive_required_criteria(
                    v["id"], a["competency_id"], a["required_level"], rubrics[a["competency_id"]])
    doc = {"_note": "D_vga for SYNTHETIC fixture vacancies, generated by scripts/derive_vacancy_criteria.py "
                    "(rule SYNTHETIC_RULE_V1). Not employer data and not scraped.",
           "criteria_source": CRITERIA_SOURCE, "requirements": requirements}
    (FIXTURES / "vacancy_criteria.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {len(requirements)} requirements")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
